-- 使用者裁：掃碼頁搬到登入後、不做免登入端點，機台用登入身分。
-- 機台身分是**新角色**，不是「沒有權限的 admin」—— API 的 ADMIN_ONLY 掛載多半只擋寫、
-- 不擋讀，零權限的 admin 讀得到全機構的學生與家長名冊；機台是放在門口、誰都摸得到的平板。
-- 新角色是 fail-closed：既有每一支掛載的角色清單都不含它，只有 /api/daily-checkins 的 POST 開給它
-- （分校強制取帳號綁的、日期強制台北今天，見 routes/daily-checkins.ts）。
--
-- 純加列舉值，「套完才部署」或「部署完才套」都安全：舊程式碼沒有任何地方寫入這個值，
-- 新程式碼在套之前也不會有人被指派成 kiosk（建帳號的 UI 在下一支）。
-- ADD VALUE 不能跟「使用這個新值」放在同一個交易 —— 這支只加值、不用它。
-- ============================================================

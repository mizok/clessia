-- ============================================================
-- 加開單堂的歷程（#1109）
--
-- 使用者裁：POST /api/sessions 加開的課堂要留歷程 → schedule_changes 寫一筆 'creation'。
-- 取名沿用前端早已在用的 'creation'（原本只是 GET /:id/changes 合成的「建立課堂」那筆）：
-- 有這一列的課堂，歷程就不再合成；照班級排程批次產生的課堂不寫列，仍然合成。
--
-- 純加列舉值，「套完才部署」或「部署完才套」都安全：舊程式碼不會寫這個值。
-- ADD VALUE 不能跟「使用這個新值」放在同一個交易 —— 這支只加值、不用它。
-- ============================================================
ALTER TYPE public.schedule_change_type ADD VALUE IF NOT EXISTS 'creation';
